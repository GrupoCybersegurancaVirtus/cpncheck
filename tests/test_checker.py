PROPS = """
P1: AG tokens(Prediction) <= 1
P2: AF marked(Prediction)
P3: AG EF marked(Prediction)
P4: AG !(dead & empty(Prediction))
P5: EG empty(Prediction)
"""


@pytest.mark.parametrize("path", [GBDT, RF], ids=["gbdt", "rf"])
def test_the_reduction_gives_the_full_verdicts_on_fixtures(path):
    full = check_cpn(path, properties=PROPS)
    reduced = check_cpn(path, properties=PROPS, reduction="stubborn")
    assert {k: r.holds for k, r in full.properties.items()} == \
        {k: r.holds for k, r in reduced.properties.items()}
    for r in reduced.properties.values():
        if r.cex is not None and r.cex.kind in ("finite", "lasso"):
            assert r.cex.replay(CPNModelChecker(path).cnet)
