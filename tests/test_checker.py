def test_the_occurrence_graph_is_deterministic():
    mc = CPNModelChecker(GBDT)
    a, b = mc.state_space(), mc.state_space()
    assert (a.n_nodes, a.n_arcs) == (b.n_nodes, b.n_arcs)
    assert a.markings == b.markings


def test_report_json_and_latex():
    result = check_cpn(RF, properties="P: AG tokens(Prediction) <= 1")
    data = json.loads(json.dumps(result.to_dict()))
    assert data["properties"]["P"]["holds"] is True
    assert data["report"]["bounds"]
    table = result.latex_table()
    assert "\\begin{table}" in table and "R1" in table and "P" in table


def test_compare_results_flags_a_regression():
    good = check_cpn(GBDT, properties="P: AF dead")
    bad = check_cpn(GBDT, properties="P: AG !dead")
    text = compare_results(good, bad)
    assert "P" in text


def test_the_askctl_script_is_written(tmp_path):
    mc = CPNModelChecker(RF, properties="P: AG tokens(Prediction) <= 1")
    path = mc.export_askctl(str(tmp_path / "q.sml"))
    text = open(path, encoding="utf-8").read()
    assert "generated by CPNCheck" in text and "CPNCHECK_REPORT" in text
    assert '("P",' in text and '("R1",' in text and "UpperInteger" in text


def test_options_reach_the_profile(tmp_path):
    """The checker hands options on without reading them."""
    from cpncheck.profile import Profile

    class Echo(Profile):
        name = "echo"

        def ctl_formulas(self, net, groups, options):
            from cpncheck.formula import AF, Dead
            self.seen = dict(options)
            return {"E1": AF(Dead())}

    profile = Echo()
    mc = CPNModelChecker(_forked(tmp_path), profile=profile,
                         options={"anything": 7})
    assert profile.seen == {"anything": 7}
    assert mc.check(options={"more": 1}).properties["E1"].holds is True
    assert mc.options == {"anything": 7, "more": 1}


def test_the_command_line_takes_profile_options(tmp_path):
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    done = subprocess.run(
        [sys.executable, "-m", "cpncheck.cli", "check", _forked(tmp_path),
         "-O", "flag=true", "-O", "labels=0,1"],
        capture_output=True, text=True, cwd=root,
        env={**os.environ, "PYTHONPATH": root})
    assert done.returncode == 0, done.stderr
    bad = subprocess.run(
        [sys.executable, "-m", "cpncheck.cli", "check", _forked(tmp_path),
         "-O", "no-equals-sign"],
        capture_output=True, text=True, cwd=root,
        env={**os.environ, "PYTHONPATH": root})
    assert bad.returncode != 0 and "KEY=VALUE" in bad.stderr


