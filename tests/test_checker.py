"""The checker on any net: reports, comparisons, scripts, counterexamples.

Everything here runs with the default profile and the user's own properties,
on CPNCheck's fixture nets and on small nets written in the tests -- no
profile plugin is involved. (The tree profile's own tests live in
pyruleanalyzer, with the profile.)
"""

import json
import os
import subprocess
import sys

import pytest

from cpncheck import CPNModelChecker, check_cpn, compare_results
from cpncheck.counterexample import Counterexample

from test_net_reading import write_net

NETS = os.path.join(os.path.dirname(__file__), "nets")
GBDT = os.path.join(NETS, "gbdt_binary.cpn")
RF = os.path.join(NETS, "rf_multiclass.cpn")


def _forked(tmp_path):
    """Two ways to end: one stops in Left, the other in Right."""
    return write_net(str(tmp_path / "fork.cpn"), {"Top": {
        "places": [("S", "Start", "INT", "1`0", None),
                   ("L", "Left", "INT", None, None),
                   ("R", "Right", "INT", None, None)],
        "trans": [("A", "GoLeft", None, None), ("B", "GoRight", None, None)],
        "arcs": [("A", "S", "PtoT", "n"), ("A", "L", "TtoP", "n"),
                 ("B", "S", "PtoT", "n"), ("B", "R", "TtoP", "n")]}})


def _loop(tmp_path):
    """A token that circles A -> B -> A forever."""
    return write_net(str(tmp_path / "loop.cpn"), {"Top": {
        "places": [("A", "A", "INT", "1`1", None), ("B", "B", "INT", None, None)],
        "trans": [("T", "Go", None, None), ("U", "Back", None, None)],
        "arcs": [("T", "A", "PtoT", "x"), ("T", "B", "TtoP", "x"),
                 ("U", "B", "PtoT", "x"), ("U", "A", "TtoP", "x")]}},
        variables=("x",))


