def test_a_violated_invariant_gives_a_finite_trace_that_replays(tmp_path):
    mc = CPNModelChecker(_forked(tmp_path), properties="P: AG empty(Left)")
    r = mc.check().properties["P"]
    assert r.holds is False and r.cex.kind == "finite"
    assert [s.name for s in r.cex.prefix] == ["GoLeft"]
    assert r.cex.replay(mc.cnet)


def test_a_run_that_never_arrives_gives_a_lasso(tmp_path):
    mc = CPNModelChecker(_loop(tmp_path), properties="P: AF dead")
    r = mc.check().properties["P"]
    assert r.cex.kind == "lasso" and r.cex.cycle
    assert r.cex.replay(mc.cnet)


def test_a_run_that_stops_too_early_is_finite(tmp_path):
    mc = CPNModelChecker(_forked(tmp_path), properties="P: AF marked(Left)")
    r = mc.check().properties["P"]
    assert r.cex.kind == "finite" and r.cex.data["ends_in"] == "a dead marking"
    assert [s.name for s in r.cex.prefix] == ["GoRight"]
    assert r.cex.replay(mc.cnet)


def test_a_precedence_violation_shows_the_until(tmp_path):
    mc = CPNModelChecker(_forked(tmp_path),
                         properties="P: !E[empty(Left) U marked(Right)]")
    r = mc.check().properties["P"]
    assert r.cex.kind == "finite" and r.cex.replay(mc.cnet)


def test_no_home_marking_names_two_components(tmp_path):
    result = check_cpn(_forked(tmp_path))
    r = result.properties["R3"]
    assert r.holds is False
    assert r.cex.data["terminal_components"] == 2


def test_a_tampered_trace_does_not_replay(tmp_path):
    mc = CPNModelChecker(_forked(tmp_path), properties="P: AG empty(Left)")
    cex = mc.check().properties["P"].cex
    other = next(i for i, t in enumerate(mc.cnet.transitions)
                 if t["name"] == "GoRight")
    cex.prefix[0].transition = other
    assert not cex.replay(mc.cnet)


def test_steps_carry_the_binding(tmp_path):
    mc = CPNModelChecker(_forked(tmp_path), properties="P: AG empty(Left)")
    step = mc.check().properties["P"].cex.prefix[0]
    assert step.binding == {"n": 0}


def test_the_counterexample_survives_serialisation(tmp_path):
    result = check_cpn(_loop(tmp_path), properties="P: AF dead")
    data = json.loads(json.dumps(result.to_dict()))
    cex = data["properties"]["P"]["counterexample"]
    assert cex["kind"] == "lasso" and cex["cycle"]


def test_a_passing_property_has_no_counterexample(tmp_path):
    result = check_cpn(_forked(tmp_path), properties="P: AF dead")
    assert result.properties["P"].holds is True
    assert result.properties["P"].cex is None


