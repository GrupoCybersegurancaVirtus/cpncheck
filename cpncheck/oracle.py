"""Ask CPN Tools itself: a headless oracle for the model checker.

The model checker in :mod:`cpncheck.checker` builds occurrence
graphs and evaluates CTL formulas in Python. Its answers are only as good as its
agreement with a reference implementation, and the reference for Coloured Petri
Nets is CPN Tools. This module runs CPN Tools' own engine without its GUI and
asks it the same questions:

1. the ``.cpn`` file is loaded and compiled by the CPN Tools 4.0.1 simulator
   (the Standard ML heap image shipped in ``CPN Tools/cpnsim``), driven through
   Access/CPN, the Java library CPN IDE uses to talk to that simulator;
2. the state-space tool is entered exactly as the GUI's *Enter State Space*
   does it -- ``ogpath`` is set and ``switch1.sml`` ... ``switch8.sml`` from
   ``CPN Tools/cpnsim/statespacefiles`` are loaded, which capture the compiled
   net and generate its occurrence-graph code;
3. ``CalculateOccGraph`` and ``CalculateSccGraph`` build the graphs, ASK-CTL is
   loaded, and every query of :meth:`CPNModelChecker.ml_program` is evaluated
   on its own, so one failing query does not hide the others.

Requirements, all found automatically on a Windows machine with CPN Tools and
CPN IDE installed: a 32-bit Java 8 runtime with the Nashorn ``jjs`` launcher,
the Access/CPN libraries bundled in the CPN IDE backend jar, and the CPN Tools
installation. :meth:`CPNToolsOracle.available` reports whether they are present;
nothing else in the package depends on this module.
"""

import glob
import hashlib
import json
import os
import re
import shutil
import socket
import subprocess
import tempfile
import time
import zipfile
from typing import Dict, List, Optional, Tuple

__all__ = ["OracleUnavailable", "CPNToolsOracle", "compare_with_oracle",
           "compare_state_space", "compare_graph_containment",
           "STATE_SPACE_QUERIES"]

_DRIVER = r"""
// Generated by cpncheck.oracle -- drives the CPN Tools simulator.
var Files = Java.type("java.nio.file.Files");
var Paths = Java.type("java.nio.file.Paths");
var JString = Java.type("java.lang.String");
var File = Java.type("java.io.File");
var job = JSON.parse(new JString(Files.readAllBytes(Paths.get(arguments[0])), "UTF-8"));
var out = { values: {}, errors: {}, log: [] };
function save() {
    Files.write(Paths.get(job.resultFile), new JString(JSON.stringify(out)).getBytes("UTF-8"));
}
var s = null;
try {
    var DOMParser = Java.type("org.cpntools.accesscpn.model.importer.DOMParser");
    var HLS = Java.type("org.cpntools.accesscpn.engine.highlevel.HighLevelSimulator");
    var Checker = Java.type("org.cpntools.accesscpn.engine.highlevel.checker.Checker");
    var net = DOMParser.parse(new File(job.net).toURI().toURL());
    s = HLS.getHighLevelSimulator();
    out.banner = String(s.getBanner());
    var c = new Checker(net, null, s);
    // checkEntireModel, step by step: its last step builds Access/CPN's Java
    // view of the marking, which types every place as untimed and so fails
    // on a timed net. The state-space tool does not use that view.
    c.localCheck();
    c.checkInitializing(job.modelDir, job.outDir);
    c.checkDeclarations();
    c.generateSerializers();
    c.checkPages();
    c.generatePlaceInstances();
    c.checkMonitors();
    c.generateNonPlaceInstances();
    c.initialiseSimulationScheduler();
    try { c.instantiateSMLInterface(); } catch (se) { out.log.push("no Java marking view"); }
    out.log.push("compiled");
    function ev(code) { return String(s.evaluate(code)); }
    ev("val ogpath = \"" + job.ogpath + "\";");
    for (var i = 1; i <= (job.stateSpace ? 8 : 0); i++) {
        var r = ev("use (ogpath^\"switch" + i + ".sml\");");
        if (r.indexOf("Error") >= 0 || r.indexOf("uncaught exception") >= 0) {
            out.errors["enter_state_space"] = "switch" + i + ": " + r.substring(0, 2000);
        }
    }
    out.log.push("entered state space");
    var t0 = java.lang.System.currentTimeMillis();
    if (job.stateSpace) {
        ev("CalculateOccGraph ();");
        ev("CalculateSccGraph ();");
        out.graph_ms = java.lang.System.currentTimeMillis() - t0;
        ev("use (ogpath^\"ASKCTL/ASKCTLloader.sml\");");
    }
    var d = ev(job.declarations);
    if (d.indexOf("Error") >= 0) { out.errors["declarations"] = d.substring(0, 4000); }
    for (var k = 0; k < job.queries.length; k++) {
        var key = job.queries[k][0], expr = job.queries[k][1];
        var q0 = java.lang.System.currentTimeMillis();
        try {
            var res = ev("val pyra_it = " + expr + ";");
            // SML breaks a long answer over several lines.
            // Escaped quotes may occur inside; Python decodes the escapes.
            var m = /val pyra_it =\s*"((?:[^"\\]|\\.)*)"\s*: string/.exec(res);
            if (m) { out.values[key] = m[1]; } else { out.errors[key] = res.substring(0, 1500); }
        } catch (qe) {
            // One query that does not compile must not hide the others.
            out.errors[key] = String(qe).substring(0, 1500);
        }
        out.log.push(key + " " + (java.lang.System.currentTimeMillis() - q0) + "ms");
    }
    // Raw queries: the REPL's own answer, value and type, as text.
    out.raw = {};
    for (var r = 0; r < job.raw.length; r++) {
        try {
            out.raw[job.raw[r][0]] = ev("val pyra_raw = " + job.raw[r][1] + ";");
        } catch (re) {
            out.raw[job.raw[r][0]] = "EXCEPTION: " + String(re).substring(0, 1500);
        }
    }
} catch (e) {
    out.errors["driver"] = String(e);
} finally {
    save();
    try { if (s !== null) { s.destroy(); } } catch (e2) {}
    java.lang.System.exit(0);
}
"""


# Exception raised when CPN Tools, CPN IDE or Java cannot be found.
class OracleUnavailable(RuntimeError):
    """The CPN Tools engine cannot be run on this machine."""


# Function to convert a Windows path into the cygwin form the simulator expects.
def _cygpath(path: str) -> str:
    """Translate ``C:\\a\\b`` into ``/cygdrive/c/a/b``.

    Args:
        path (str): A Windows path.

    Returns:
        str: The cygwin path.
    """
    path = os.path.abspath(path).replace("\\", "/")
    m = re.match(r"^([A-Za-z]):/(.*)$", path)
    return f"/cygdrive/{m.group(1).lower()}/{m.group(2)}" if m else path


# Class running the CPN Tools engine headlessly.
class CPNToolsOracle:
    """Headless access to the CPN Tools 4.0.1 simulator and state-space tool.

    Example:
        >>> oracle = CPNToolsOracle()
        >>> if oracle.available():
        ...     report = compare_with_oracle("files/gbdt_final.cpn", oracle)
    """

    SIMULATOR_FILES = (
        ("cpnmld.x86-cygwin.exe", "cpnmld.x86-cygwin"),
        ("run.x86-cygwin.exe", "run.x86-cygwin"),
        ("cpn.ML.x86-cygwin", "cpn.ML.x86-cygwin"),
        ("cygwin1.dll", "cygwin1.dll"),
        ("cyggcc_s-1.dll", "cyggcc_s-1.dll"),
    )
    PORT = 20001

    # Method to locate the tools the oracle needs.
    def __init__(self, cpntools_dir: Optional[str] = None,
                 backend_jar: Optional[str] = None, jjs: Optional[str] = None,
                 cache_dir: Optional[str] = None):
        """Find CPN Tools, the Access/CPN libraries and a Nashorn launcher.

        Args:
            cpntools_dir (str, optional): CPN Tools installation directory.
            backend_jar (str, optional): The CPN IDE backend jar, which bundles
                the Access/CPN libraries.
            jjs (str, optional): Path to Java 8's ``jjs``.
            cache_dir (str, optional): Where the libraries and the simulator
                are staged (defaults to a folder in the user's cache).
        """
        pf86 = os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")
        pf = os.environ.get("ProgramFiles", r"C:\Program Files")
        self.cpntools_dir = cpntools_dir or os.path.join(pf86, "CPN Tools")
        self.backend_jar = backend_jar or next(iter(sorted(glob.glob(os.path.join(
            pf86, "CPN IDE", "resources", "backend", "cpn-ide-back-*.jar")) + glob.glob(
            os.path.join(pf, "CPN IDE", "resources", "backend", "cpn-ide-back-*.jar")))),
            None)
        self.jjs = jjs or next(iter(sorted(glob.glob(os.path.join(
            pf86, "Java", "jre1.8*", "bin", "jjs.exe")) + glob.glob(os.path.join(
            pf, "Java", "jre1.8*", "bin", "jjs.exe")) + glob.glob(os.path.join(
            pf, "Java", "jdk1.8*", "bin", "jjs.exe")))), None)
        base = cache_dir or os.path.join(
            os.environ.get("LOCALAPPDATA", tempfile.gettempdir()),
            "pyruleanalyzer", "cpntools-oracle")
        self.cache_dir = base
        self.lib_dir = os.path.join(base, "lib")
        self.tmp_dir = os.path.join(base, "tmp")
        self.sim_dir = os.path.join(self.tmp_dir, "accesscpn", "simulator")
        self.driver = os.path.join(base, "driver.js")

    # Property returning the CPN Tools simulator directory.
    @property
    def cpnsim(self) -> str:
        """The ``cpnsim`` folder of the CPN Tools installation.

        Returns:
            str: Its path.
        """
        return os.path.join(self.cpntools_dir, "cpnsim")

    # Method to tell whether the oracle can run here.
    def available(self) -> bool:
        """Whether every required component was found.

        Returns:
            bool: True if :meth:`run` can be used.
        """
        return not self.missing()

    # Method to list the missing components.
    def missing(self) -> List[str]:
        """The components that could not be found.

        Returns:
            list: Human-readable names, empty when everything is present.
        """
        out = []
        if not os.path.isfile(os.path.join(self.cpnsim, "cpn.ML.x86-cygwin")):
            out.append(f"CPN Tools simulator in {self.cpnsim}")
        if not os.path.isdir(os.path.join(self.cpnsim, "statespacefiles")):
            out.append("CPN Tools state-space files")
        if not self.backend_jar or not os.path.isfile(self.backend_jar):
            out.append("CPN IDE backend jar (Access/CPN libraries)")
        if not self.jjs or not os.path.isfile(self.jjs):
            out.append("Java 8 jjs (Nashorn)")
        return out

    # Method to prepare libraries, simulator copy and driver script.
    def _stage(self):
        """Extract the Access/CPN libraries and copy the 4.0.1 simulator.

        Access/CPN starts the simulator found in ``<java tmp>/accesscpn/
        simulator`` and only extracts its own bundled one when that folder is
        empty; pointing Java's temp directory at a folder holding CPN Tools'
        files makes it run CPN Tools 4.0.1's simulator.

        Raises:
            OracleUnavailable: If a component is missing.
        """
        missing = self.missing()
        if missing:
            raise OracleUnavailable("missing: " + "; ".join(missing))
        os.makedirs(self.lib_dir, exist_ok=True)
        os.makedirs(self.sim_dir, exist_ok=True)
        if not glob.glob(os.path.join(self.lib_dir, "*.jar")):
            with zipfile.ZipFile(self.backend_jar) as z:
                for name in z.namelist():
                    if name.startswith("BOOT-INF/lib/") and name.endswith(".jar"):
                        with open(os.path.join(self.lib_dir, name.split("/")[-1]),
                                  "wb") as fh:
                            fh.write(z.read(name))
        for src, dst in self.SIMULATOR_FILES:
            target = os.path.join(self.sim_dir, dst)
            source = os.path.join(self.cpnsim, src)
            if not os.path.exists(target) or \
                    os.path.getsize(target) != os.path.getsize(source):
                shutil.copyfile(source, target)
        with open(self.driver, "w", encoding="utf-8") as fh:
            fh.write(_DRIVER)

    # Method to report the identity of the simulator image being used.
    def simulator_digest(self) -> str:
        """SHA-256 of the staged simulator heap image.

        Returns:
            str: The hex digest (records which engine answered).
        """
        self._stage()
        h = hashlib.sha256()
        with open(os.path.join(self.sim_dir, "cpn.ML.x86-cygwin"), "rb") as fh:
            for block in iter(lambda: fh.read(1 << 20), b""):
                h.update(block)
        return h.hexdigest()

    # Method to check that no other simulator daemon owns the port.
    def _port_free(self) -> bool:
        """Whether the simulator daemon port is free.

        A daemon left running by CPN IDE would be reused by Access/CPN and
        would answer with a different simulator image.

        Returns:
            bool: True if nothing listens on the port.
        """
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            sock.settimeout(0.5)
            return sock.connect_ex(("127.0.0.1", self.PORT)) != 0

    # Method to evaluate queries on a net with the CPN Tools engine.
    def run(self, cpn_path: str, declarations: str,
            queries: Dict[str, str], timeout: int = 1800,
            raw: Optional[Dict[str, str]] = None,
            state_space: bool = True) -> Dict[str, object]:
        """Load, compile and explore a net in CPN Tools, then evaluate queries.

        Args:
            cpn_path (str): The ``.cpn`` file.
            declarations (str): CPN ML declarations evaluated before the queries.
            queries (dict): ``{key: string-valued ML expression}``.
            timeout (int): Seconds before the run is abandoned.
            raw (dict, optional): ``{key: ML expression of any type}``; the
                answer is the REPL's text (``val pyra_raw = [1,2] : int
                list``), for :func:`parse_sml_value`.
            state_space (bool): Enter the state-space tool and build the
                graph first; not needed to evaluate expressions.

        Returns:
            dict: ``{"values", "errors", "raw", "banner", "graph_ms",
            "elapsed"}``.

        Raises:
            OracleUnavailable: If the engine cannot be started.
        """
        self._stage()
        if not self._port_free():
            raise OracleUnavailable(
                f"port {self.PORT} is in use: close CPN IDE / CPN Tools or end any "
                "cpnmld process, so the CPN Tools 4.0.1 simulator is started")
        cpn_path = os.path.abspath(cpn_path)
        work = tempfile.mkdtemp(prefix="oracle_", dir=self.cache_dir)
        job_file = os.path.join(work, "job.json")
        result_file = os.path.join(work, "result.json")
        out_dir = os.path.join(work, "out")
        os.makedirs(out_dir, exist_ok=True)
        job = {
            "net": cpn_path,
            "modelDir": os.path.dirname(cpn_path) + "\\",
            "outDir": out_dir + "\\",
            "ogpath": _cygpath(os.path.join(self.cpnsim, "statespacefiles")) + "/",
            "declarations": declarations,
            "queries": [[k, v] for k, v in queries.items()],
            "raw": [[k, v] for k, v in (raw or {}).items()],
            "stateSpace": state_space,
            "resultFile": result_file,
        }
        with open(job_file, "w", encoding="utf-8") as fh:
            json.dump(job, fh)
        # Nashorn's option parser rejects class-path entries carrying a drive
        # letter, so the jars are given relative to the cache directory.
        classpath = os.pathsep.join(
            "lib/" + os.path.basename(p)
            for p in sorted(glob.glob(os.path.join(self.lib_dir, "*.jar"))))
        cmd = [self.jjs, f"-J-Djava.io.tmpdir={self.tmp_dir}", "-cp", classpath,
               "driver.js", "--", job_file]
        t0 = time.time()
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout,
                              errors="replace", cwd=self.cache_dir)
        elapsed = time.time() - t0
        if not os.path.exists(result_file):
            raise OracleUnavailable("the CPN Tools engine produced no result:\n"
                                    + (proc.stdout + proc.stderr)[-3000:])
        with open(result_file, encoding="utf-8") as fh:
            result = json.load(fh)
        # String answers arrive with SML's escapes (quotes, newlines,
        # backslashes); decode them.
        from .smlvalue import _unescape
        result["values"] = {k: _unescape(v)
                            for k, v in result.get("values", {}).items()}
        result["elapsed"] = elapsed
        shutil.rmtree(work, ignore_errors=True)
        return result


#: The state-space statistics asked of CPN Tools by :func:`compare_state_space`.
STATE_SPACE_QUERIES = {
    "nodes": "Int.toString (NoOfNodes ())",
    "arcs": "Int.toString (NoOfArcs ())",
    "scc_nodes": "Int.toString (SccNoOfNodes ())",
    "scc_arcs": "Int.toString (SccNoOfArcs ())",
    "dead": "Int.toString (length (ListDeadMarkings ()))",
    "home": "Int.toString (length (ListHomeMarkings ()))",
}


# Function to compare the occurrence graph of any net with CPN Tools'.
def compare_state_space(cpn_path: str, oracle: Optional[CPNToolsOracle] = None,
                        max_nodes: int = 200_000,
                        timeout: int = 1800,
                        compat: Optional[str] = None) -> Dict[str, object]:
    """Build the occurrence graph in both engines and compare its statistics.

    Unlike :func:`compare_with_oracle` this needs no profile, so it applies to
    any net CPNCheck can read: it is how support for a new kind of net is
    shown to agree with CPN Tools rather than assumed to.

    Args:
        cpn_path (str): The ``.cpn`` file.
        oracle (CPNToolsOracle, optional): The oracle; created when omitted.
        max_nodes (int): Budget for CPNCheck's graph.
        timeout (int): Seconds allowed for CPN Tools.
        compat (str, optional): Passed to :class:`ColouredNet`. A timed net
            needs ``"cpntools-4.0.1"`` to be comparable: that version's state
            space tool shifts timestamps when it expands a node (see
            :meth:`ColouredNet._expansion_view`).

    Returns:
        dict: ``{"net", "rows": [(key, cpncheck, cpntools, agree)], "agree",
        "errors"}``.

    Raises:
        UnsupportedNet: When CPNCheck cannot read the net.
    """
    from .coloured import ColouredNet
    from .net import CPNNet
    from .statespace import build_state_space

    ss = build_state_space(ColouredNet(CPNNet(cpn_path), compat=compat),
                           max_nodes)
    mine = {"nodes": ss.n_nodes, "arcs": ss.n_arcs, "scc_nodes": ss.n_sccs,
            "scc_arcs": ss.n_scc_arcs, "dead": len(ss.dead),
            "home": len(ss.home)}
    oracle = oracle or CPNToolsOracle()
    answer = oracle.run(cpn_path, "", STATE_SPACE_QUERIES, timeout=timeout)
    rows: List[Tuple[str, str, Optional[str], bool]] = []
    for key in STATE_SPACE_QUERIES:
        theirs = answer["values"].get(key)
        ours = str(mine[key]) if ss.complete else None
        rows.append((key, ours, theirs, ours is not None and ours == theirs))
    return {"net": cpn_path, "rows": rows, "agree": all(r[3] for r in rows),
            "errors": answer.get("errors", {})}


#: Separates the places of one marking in an answer (a string token may hold
#: "#", but hardly this).
_SEP = "|#|"


# Function to read a multiset as CPN Tools prints it.
def _printed_multiset(text: str) -> Tuple[str, ...]:
    """``2`(p,0)@0+++ 1`(q,0)@3`` as a sorted tuple of token texts.

    Args:
        text (str): The output of ``st_Mark``.

    Returns:
        tuple: One entry per token, spaces removed.
    """
    text = re.sub(r"^\S+ \d+: ", "", text.strip())
    # SML breaks long answers; the line breaks may come escaped.
    text = re.sub(r"\s+|\\n", "", text)
    if text == "empty":
        return ()
    out: List[str] = []
    for part in re.split(r"\+\+\+?", text):
        m = re.match(r"(\d+)`(.*)$", part)
        if m is None:
            out.append(part)
        else:
            out += [m.group(2)] * int(m.group(1))
    return tuple(sorted(out))


# Function to check that CPN Tools' graph is contained in CPNCheck's.
def compare_graph_containment(cpn_path: str,
                              oracle: Optional[CPNToolsOracle] = None,
                              max_nodes: int = 20_000, timeout: int = 1800,
                              compat: Optional[str] = None
                              ) -> Dict[str, object]:
    """Match every node and arc of CPN Tools' occurrence graph in CPNCheck's.

    Equal statistics are the check for nets whose occurrence graph is
    unique. A timed net is not one of them: an occurrence may take any of
    several ready tokens of one value, CPNCheck explores every choice and
    CPN Tools 4.0.1 some of them (not always the same ones). There the
    check is containment: each node CPN Tools finds is a CPNCheck node with
    the same marking and clock, and each of its arcs is a CPNCheck arc.

    Markings are compared as CPN Tools prints them, so this suits nets whose
    colours print alike in both (integers, enumerations, tuples of them).

    Args:
        cpn_path (str): The ``.cpn`` file.
        oracle (CPNToolsOracle, optional): The oracle; created when omitted.
        max_nodes (int): Budget for both graphs.
        timeout (int): Seconds allowed for CPN Tools (per run).
        compat (str, optional): Passed to :class:`ColouredNet`.

    Returns:
        dict: ``{"net", "nodes": (cpncheck, cpntools), "arcs": (...),
        "dead": (...), "missing_nodes", "missing_arcs", "contained",
        "errors"}``.

    Raises:
        UnsupportedNet: When CPNCheck cannot read the net.
    """
    from .coloured import ColouredNet
    from .net import CPNNet
    from .statespace import build_state_space

    net = ColouredNet(CPNNet(cpn_path), compat=compat)
    ss = build_state_space(net, max_nodes)
    oracle = oracle or CPNToolsOracle()
    first = oracle.run(cpn_path, "", {"n": STATE_SPACE_QUERIES["nodes"],
                                      "dead": STATE_SPACE_QUERIES["dead"]},
                       timeout=timeout)
    n_theirs = int(first["values"].get("n", "0"))
    if not ss.complete or n_theirs == 0 or n_theirs > max_nodes:
        return {"net": cpn_path, "contained": False,
                "nodes": (ss.n_nodes, n_theirs), "errors": first["errors"],
                "missing_nodes": None, "missing_arcs": None}
    places = net.places
    # CPN Tools may build a slightly different graph on the second run (see
    # above): that run reports its own size, and a margin covers growth.
    asked = n_theirs + n_theirs // 10 + 50
    queries = {"n": STATE_SPACE_QUERIES["nodes"],
               "dead": STATE_SPACE_QUERIES["dead"]}
    for n in range(1, asked + 1):
        parts = [f"st_Mark.{p['ml']} {p.get('instance', 1)} {n}" for p in places]
        if net.timed:
            parts.append(f"CPN'Time.mkstr (CreationTime {n})")
        queries[f"m{n}"] = f' ^ "{_SEP}" ^ '.join(parts)
        queries[f"s{n}"] = ('String.concatWith "," (map (fn cpnq_a => '
                            f'Int.toString (DestNode cpnq_a)) (OutArcs {n}))')
    answer = oracle.run(cpn_path, "val _ = Control.Print.stringDepth := 1000000;",
                        queries, timeout=timeout)
    values = answer["values"]
    n_theirs = int(values.get("n", "0"))
    if n_theirs > asked:
        return {"net": cpn_path, "contained": False,
                "nodes": (ss.n_nodes, n_theirs),
                "errors": {"oracle": "CPN Tools' graph grew between runs"},
                "missing_nodes": None, "missing_arcs": None}
    theirs: Dict[int, tuple] = {}
    for n in range(1, n_theirs + 1):
        text = values.get(f"m{n}")
        if text is None:
            continue
        fields = text.split(_SEP)
        marking = tuple(_printed_multiset(f) for f in fields[:len(places)])
        if net.timed:
            marking += (fields[-1].strip(),)
        theirs[n] = marking

    from .colourset import mkstr
    from .cpnml import TimedToken
    from .mllib import sml_int

    sets = net.declarations.colsets

    def written(token, colset):
        # As CPN Tools writes a token: its mkstr, and @time when timed.
        if isinstance(token, TimedToken):
            return mkstr(token[0], colset, sets) + "@" + sml_int(token[1])
        return mkstr(token, colset, sets)

    def ours_of(m):
        key = tuple(tuple(sorted(
            re.sub(r"\s+", "", written(t, sets.get(places[i].get("colset"))))
            for t in m[i])) for i in range(len(places)))
        return key + ((str(m[-1]),) if net.timed else ())

    ours = {ours_of(m): i for i, m in enumerate(ss.markings)}
    missing_nodes = sorted(n for n, m in theirs.items() if m not in ours)
    missing_arcs = 0
    arcs_theirs = 0
    for n, m in theirs.items():
        dests = [int(d) for d in values.get(f"s{n}", "").split(",") if d]
        arcs_theirs += len(dests)
        if m not in ours:
            continue
        reach = {ours_of(ss.markings[d]) for _t, _k, d in ss.succ[ours[m]]}
        missing_arcs += sum(1 for d in dests if theirs.get(d) not in reach)
    contained = (len(theirs) == n_theirs and not missing_nodes
                 and not missing_arcs)
    return {"net": cpn_path, "contained": contained,
            "nodes": (ss.n_nodes, n_theirs), "arcs": (ss.n_arcs, arcs_theirs),
            "dead": (len(ss.dead), int(values.get("dead", "-1"))),
            "missing_nodes": missing_nodes, "missing_arcs": missing_arcs,
            "errors": {k: v for k, v in answer.get("errors", {}).items()
                       if int(k[1:] if k[1:].isdigit() else 0) <= n_theirs}}


# Function to compare the model checker with CPN Tools on one net.
def compare_with_oracle(cpn_path: str, oracle: Optional[CPNToolsOracle] = None,
                        timeout: int = 1800, properties=None,
                        options: Optional[Dict[str, object]] = None
                        ) -> Dict[str, object]:
    """Run both engines on a net and compare every value.

    Args:
        cpn_path (str): The ``.cpn`` file (its own initial marking is used).
        oracle (CPNToolsOracle, optional): The oracle; created when omitted.
        timeout (int): Seconds allowed for CPN Tools.
        properties (optional): User properties, compared too.
        options (dict, optional): Settings for the net's profile.

    Returns:
        dict: ``{"net", "rows": [(key, pyra, cpntools, agree)], "agree",
        "errors", "banner", "result"}``.
    """
    from .checker import CPNModelChecker

    oracle = oracle or CPNToolsOracle()
    checker = CPNModelChecker(cpn_path, properties=properties,
                              options=options)
    result = checker.check()
    decl, queries = checker.ml_program()
    answer = oracle.run(cpn_path, decl, queries, timeout=timeout)
    rows: List[Tuple[str, str, Optional[str], bool]] = []
    for key in queries:
        mine = result.oracle.get(key)
        theirs = answer["values"].get(key)
        rows.append((key, mine, theirs, mine is not None and mine == theirs))
    return {
        "net": cpn_path, "rows": rows, "agree": all(r[3] for r in rows),
        "errors": answer.get("errors", {}), "banner": answer.get("banner"),
        "graph_ms": answer.get("graph_ms"), "elapsed": answer.get("elapsed"),
        "result": result,
    }
